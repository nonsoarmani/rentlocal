// scripts/import-osm.mjs
// Pulls equipment-rental businesses for ONE city from OpenStreetMap (free) and writes a .sql file
// that you then load into your D1 database.
//
// Usage:   npm run import:city -- "Austin" TX
// Output:  data/import-tx-austin.sql
//
// Optional:  --stocks skid-steer-rental,mini-excavator-rental
//   Marks EVERY yard found as stocking those machines. Only use this for machines you have verified.
//   Without it, yards are imported with NO inventory (and so will not appear on machine pages yet).
//
// Data (c) OpenStreetMap contributors, ODbL — the site footer carries the required credit.

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';

const UA = 'RentLocalMachinery-importer/1.0 (contact: your-email@example.com)'; // OSM asks for an identifying User-Agent
const OVERPASS = 'https://overpass-api.de/api/interpreter';
const NOMINATIM = 'https://nominatim.openstreetmap.org/search';
const VALID_SLUGS = ['skid-steer-rental', 'mini-excavator-rental', 'boom-lift-rental'];

// ---------- helpers (exported for testing) ----------
export const slugify = (s) =>
  s.toLowerCase().trim().replace(/['’.]/g, '').replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

export const sqlStr = (v) => (v == null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
export const sqlNum = (v) => (Number.isFinite(v) ? String(v) : 'NULL');

/** Tidy a phone number to (512) 555-0101 when it is a normal 10-digit US number. */
export function cleanPhone(raw) {
  if (!raw) return null;
  const first = String(raw).split(/[;,]/)[0];
  const d = first.replace(/\D/g, '').replace(/^1(?=\d{10}$)/, '');
  return d.length === 10 ? `(${d.slice(0, 3)}) ${d.slice(3, 6)}-${d.slice(6)}` : first.trim() || null;
}

export const cleanWebsite = (raw) => {
  if (!raw) return null;
  const w = String(raw).split(';')[0].trim();
  return /^https?:\/\//i.test(w) ? w : `https://${w}`;
};

/** Turn raw OSM elements into yard records for one state. */
export function toYards(elements, fallbackCity, stateCode) {
  const yards = [];
  const seenNames = new Set();
  const usedSlugs = new Set();
  for (const el of elements) {
    const t = el.tags ?? {};
    const name = (t.name ?? '').trim();
    if (!name) continue; // unnamed shops are useless to us
    const lat = el.lat ?? el.center?.lat;
    const lon = el.lon ?? el.center?.lon;
    const street = [t['addr:housenumber'], t['addr:street']].filter(Boolean).join(' ') || null;
    const city = (t['addr:city'] ?? fallbackCity).trim();
    const state = (t['addr:state'] ?? stateCode).toUpperCase();
    if (state.length === 2 && state !== stateCode) continue; // wrong state (bounding box spill-over)

    // De-duplicate: the same shop is often mapped twice (building + point)
    const key = `${slugify(name)}|${slugify(city)}|${(street ?? '').toLowerCase()}`;
    if (seenNames.has(key)) continue;
    seenNames.add(key);

    // Slug must be unique per state (matches the DB's unique index)
    let slug = slugify(name);
    if (usedSlugs.has(slug)) slug = `${slug}-${slugify(city)}`;
    for (let n = 2; usedSlugs.has(slug); n++) slug = `${slugify(name)}-${slugify(city)}-${n}`;
    usedSlugs.add(slug);

    yards.push({
      name, slug, address: street, city, state,
      zip: (t['addr:postcode'] ?? '').slice(0, 5),
      phone: cleanPhone(t.phone ?? t['contact:phone']),
      email: t.email ?? t['contact:email'] ?? null,
      website: cleanWebsite(t.website ?? t['contact:website']),
      lat, lon,
    });
  }
  return yards;
}

/** Build the SQL. Safe to run twice: INSERT OR IGNORE skips yards that already exist (state+slug). */
export function toSql(yards, stocks) {
  const lines = [
    '-- Generated by scripts/import-osm.mjs. Data (c) OpenStreetMap contributors (ODbL).',
  ];
  for (const y of yards) {
    lines.push(
      `INSERT OR IGNORE INTO rental_yards (name, slug, address, city, state, zip_code, phone, email, website, latitude, longitude, is_partner) VALUES (${[
        sqlStr(y.name), sqlStr(y.slug), sqlStr(y.address), sqlStr(y.city), sqlStr(y.state), `'${y.zip.replace(/\D/g, '')}'`, // zip_code is NOT NULL in the schema: use '' when unknown
        sqlStr(y.phone), sqlStr(y.email), sqlStr(y.website), sqlNum(y.lat), sqlNum(y.lon),
      ].join(', ')}, 0);`,
    );
    for (const s of stocks) {
      lines.push(
        `INSERT OR IGNORE INTO yard_inventory (yard_id, equipment_id) SELECT y.id, e.id FROM rental_yards y, equipment_types e WHERE y.state = ${sqlStr(y.state)} AND y.slug = ${sqlStr(y.slug)} AND e.slug = ${sqlStr(s)};`,
      );
    }
  }
  return lines.join('\n') + '\n';
}

// ---------- network ----------
async function getJson(url, init = {}) {
  const res = await fetch(url, { ...init, headers: { 'User-Agent': UA, ...(init.headers ?? {}) } });
  if (!res.ok) throw new Error(`${new URL(url).host} answered ${res.status} ${res.statusText}`);
  return res.json();
}

async function findBox(city, stateCode) {
  const url = `${NOMINATIM}?${new URLSearchParams({ city, state: stateCode, country: 'US', format: 'json', limit: '1' })}`;
  const hit = (await getJson(url))[0];
  if (!hit) throw new Error(`Could not find "${city}, ${stateCode}" on the map. Check the spelling.`);
  const [s, n, w, e] = hit.boundingbox.map(Number); // south, north, west, east
  const pad = 0.05; // ~3 miles, so nearby suburbs' yards are included
  return `${s - pad},${w - pad},${n + pad},${e + pad}`;
}

async function fetchOverpass(box) {
  // Equipment / tool rental businesses. OSM has no "heavy equipment" tag, so we search several tags.
  const q = `[out:json][timeout:60];
(
  nwr["shop"="tool_hire"](${box});
  nwr["shop"="rental"]["rental"~"tool|machine|construction|equipment|heavy",i](${box});
  nwr["shop"="rental"]["name"~"equipment|tool|machinery|rent-?all|rentals",i](${box});
  nwr["amenity"="rental"]["name"~"equipment|tool|machinery|rent-?all",i](${box});
);
out center tags;`;
  const data = await getJson(OVERPASS, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: `data=${encodeURIComponent(q)}`,
  });
  return data.elements ?? [];
}

// ---------- main ----------
async function main() {
  const args = process.argv.slice(2);
  const stocksIdx = args.indexOf('--stocks');
  const stocks = stocksIdx >= 0 ? (args[stocksIdx + 1] ?? '').split(',').filter(Boolean) : [];
  const fileIdx = args.indexOf('--from-file'); // offline testing only
  const positional = args.filter((a, i) => !a.startsWith('--') && i !== stocksIdx + 1 && i !== fileIdx + 1);
  const [city, stateRaw] = positional;

  if (!city || !stateRaw || stateRaw.length !== 2) {
    console.error('Usage: npm run import:city -- "Austin" TX   (city name, then 2-letter state code)');
    process.exit(1);
  }
  const bad = stocks.filter((s) => !VALID_SLUGS.includes(s));
  if (bad.length) {
    console.error(`Unknown machine(s): ${bad.join(', ')}\nValid: ${VALID_SLUGS.join(', ')}`);
    process.exit(1);
  }
  const stateCode = stateRaw.toUpperCase();

  let elements;
  if (fileIdx >= 0) {
    elements = JSON.parse(readFileSync(args[fileIdx + 1], 'utf8')).elements;
  } else {
    console.log(`Looking up ${city}, ${stateCode} ...`);
    const box = await findBox(city, stateCode);
    console.log('Searching OpenStreetMap for equipment rental businesses ...');
    elements = await fetchOverpass(box);
  }

  const yards = toYards(elements, city, stateCode);
  if (yards.length === 0) {
    console.log('No named rental businesses found for that city. Try a bigger nearby city.');
    return;
  }
  mkdirSync('data', { recursive: true });
  const file = `data/import-${stateCode.toLowerCase()}-${slugify(city)}.sql`;
  writeFileSync(file, toSql(yards, stocks));

  console.log(`\nFound ${yards.length} rental businesses:`);
  for (const y of yards) console.log(`  - ${y.name} (${y.city})${y.phone ? '  ' + y.phone : ''}`);
  console.log(`\nSaved: ${file}`);
  if (!stocks.length) {
    console.log('\nNOTE: these yards have no machines assigned yet, so they will not show on machine pages.');
    console.log('Check each yard\'s website, then re-run with  --stocks skid-steer-rental,boom-lift-rental');
  }
  console.log(`\nNext: npm run db:import:local -- ${file}`);
}

// Only run main() when executed directly (so tests can import the helpers)
if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => { console.error('\nSomething went wrong:', e.message); process.exit(1); });
}
